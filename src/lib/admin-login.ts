import { createHmac } from "node:crypto";
import { ADMIN_COOKIE_NAME } from "./admin-auth";

const BODY_LIMIT = 4096;
export type AdminLoginDependencies = {
  secret: string | undefined;
  trustedIpHeader?: string;
  limited: (keys: string[]) => Promise<boolean>;
  verifyPassword: (candidate: string) => boolean;
  createSessionToken: () => Promise<string>;
  secureCookie: boolean;
};

/** A redirect is always a same-site admin path. Reject URL parser whitespace
 * normalization and backslashes, not just protocol-relative `//` inputs. */
export function safeAdminRedirect(value: string, origin: string): string {
  if (!value.startsWith("/") || value.startsWith("//") || /[\\\u0000-\u0020\u007f]/.test(value)) return "/admin";
  try {
    const url = new URL(value, origin);
    if (url.origin !== origin || (url.pathname !== "/admin" && !url.pathname.startsWith("/admin/"))) return "/admin";
    return `${url.pathname}${url.search}${url.hash}`;
  } catch { return "/admin"; }
}

/** Next's request URL may normalize localhost while Host preserves 127.0.0.1.
 * Trust the received Host, not caller-supplied forwarding headers. */
export function adminRequestOrigin(request: Request): string | null {
  try {
    const url = new URL(request.url);
    const host = request.headers.get("host") ?? url.host;
    if (!/^[a-z0-9.:[\]-]+$/i.test(host)) return null;
    return new URL(`${url.protocol}//${host}`).origin;
  } catch { return null; }
}

async function formBody(request: Request): Promise<URLSearchParams> {
  if (!request.body) throw new Error("body");
  const reader = request.body.getReader();
  const chunks: Uint8Array[] = [];
  let size = 0;
  try {
    while (true) {
      const next = await reader.read();
      if (next.done) break;
      size += next.value.byteLength;
      if (size > BODY_LIMIT) { await reader.cancel(); throw new Error("large"); }
      chunks.push(next.value);
    }
  } finally { reader.releaseLock(); }
  const bytes = new Uint8Array(size);
  let offset = 0;
  for (const chunk of chunks) { bytes.set(chunk, offset); offset += chunk.length; }
  return new URLSearchParams(new TextDecoder("utf-8", { fatal: true }).decode(bytes));
}

export function createAdminLoginHandler(dependencies: AdminLoginDependencies) {
  return async (request: Request): Promise<Response> => {
    const headers = { "Cache-Control": "private, no-store", "X-Content-Type-Options": "nosniff" };
    const failure = (message: string, status: number) => Response.json({ message }, { status, headers });
    const origin = adminRequestOrigin(request);
    if (!origin || request.headers.get("origin") !== origin || request.headers.get("sec-fetch-site") === "cross-site") return failure("Submit the sign-in form from this website.", 403);
    if (request.headers.get("content-type")?.split(";")[0].trim().toLowerCase() !== "application/x-www-form-urlencoded") return failure("Use the admin sign-in form.", 415);
    const length = request.headers.get("content-length");
    if (length && (!/^\d+$/.test(length) || Number(length) > BODY_LIMIT)) return failure("The sign-in request is too large.", 413);
    let form: URLSearchParams;
    try { form = await formBody(request); }
    catch (error) { return failure("Invalid sign-in request.", error instanceof Error && error.message === "large" ? 413 : 400); }
    const password = form.get("password") ?? "";
    const from = safeAdminRedirect(form.get("from") ?? "", origin);
    if (password.length > 256) return failure("Invalid sign-in request.", 400);
    if (!dependencies.secret || dependencies.secret.length < 32) return failure("Sign-in is temporarily unavailable. Contact the site owner.", 503);
    const hash = (value: string) => createHmac("sha256", dependencies.secret!).update(value).digest("hex");
    const keys = [hash("admin-login:global")];
    if (dependencies.trustedIpHeader) {
      const ip = request.headers.get(dependencies.trustedIpHeader)?.trim();
      if (ip && ip.length <= 64 && /^[\da-fA-F:.]+$/.test(ip)) keys.push(hash(`admin-login:ip:${ip}`));
    }
    try {
      if (await dependencies.limited(keys)) return Response.json({ message: "Too many sign-in attempts. Try again later." }, { status: 429, headers: { ...headers, "Retry-After": "3600" } });
      if (!password || !dependencies.verifyPassword(password)) {
        const login = new URL("/admin/login", origin);
        login.searchParams.set("error", "1");
        login.searchParams.set("from", from);
        return new Response(null, { status: 303, headers: { ...headers, Location: login.href } });
      }
      const token = await dependencies.createSessionToken();
      // Token generated by existing HMAC auth: fixed numeric expiry + hex signature.
      if (!/^\d+\.[a-f0-9]{64}$/.test(token)) throw new Error("invalid_token");
      return new Response(null, { status: 303, headers: {
        ...headers,
        Location: new URL(from, origin).href,
        "Set-Cookie": `${ADMIN_COOKIE_NAME}=${token}; Path=/; HttpOnly; SameSite=Lax; Max-Age=604800${dependencies.secureCookie ? "; Secure" : ""}`,
      } });
    } catch { return failure("Sign-in is temporarily unavailable. Please try again later.", 503); }
  };
}
